update public.tg8_costs set sort_order =
  case building
    when '도시센터' then 0
    when '대사관' then 10
    when '보병대' then 20
    when '기병대' then 30
    when '궁병대' then 40
    when '지휘부' then 50
    when '병원' then 60
    when '전쟁아카데미' then 70
    else 90 end
  + case stage
    when 'Lv30→TG1' then 1
    when 'TG1→TG2' then 2
    when 'TG2→TG3' then 3
    when 'TG3→TG4' then 4
    when 'TG4→TG5' then 5
    when 'TG5→TG6' then 6
    when 'TG6→TG7' then 7
    when 'TG7→TG8' then 8
    else 9 end;
